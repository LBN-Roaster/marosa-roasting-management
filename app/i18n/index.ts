export function createI18n(locale: Locale): i18n {
  const instance = createInstance();
  void instance.use(initReactI18next).init({
    resources,
    lng: locale,
    fallbackLng: "en",
    supportedLngs: ["en", "vi"],
    defaultNS: "common",
    fallbackNS: "common",
    initAsync: false,
    interpolation: { escapeValue: false },
  });
  return instance;
}

export function localeFromRequest(request: Request): Locale {
  const cookie = request.headers.get("Cookie") ?? "";
  const savedLocale = cookie.match(/(?:^|;\s*)marosa_locale=(en|vi)(?:;|$)/)?.[1];
  if (savedLocale === "vi" || savedLocale === "en") return savedLocale;

  const acceptedLanguage = request.headers.get("Accept-Language")?.toLowerCase() ?? "";
  return acceptedLanguage.split(",").some((language) => language.trim().startsWith("vi")) ? "vi" : "en";
}
